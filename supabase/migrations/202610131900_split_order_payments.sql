-- Permite dividir una cuenta por persona/productos y registrar varios medios
-- de pago por grupo. Cada comanda queda pagada en una sola transacción.

CREATE TABLE IF NOT EXISTS public.order_payment_groups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  user_id integer REFERENCES public.users(id),
  payer_name text,
  group_amount numeric(10, 2) NOT NULL CHECK (group_amount >= 0),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.order_payment_group_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_group_id bigint NOT NULL REFERENCES public.order_payment_groups(id) ON DELETE CASCADE,
  order_item_id integer NOT NULL REFERENCES public.order_items(id),
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(10, 2) NOT NULL CHECK (unit_price >= 0),
  subtotal numeric(10, 2) NOT NULL CHECK (subtotal >= 0),
  UNIQUE (payment_group_id, order_item_id)
);

CREATE TABLE IF NOT EXISTS public.order_payment_tenders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_group_id bigint NOT NULL REFERENCES public.order_payment_groups(id) ON DELETE CASCADE,
  payment_method text NOT NULL CHECK (payment_method IN ('efectivo', 'tarjeta', 'transferencia')),
  amount numeric(10, 2) NOT NULL CHECK (amount > 0),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS order_payment_groups_order_id_idx
  ON public.order_payment_groups (order_id);
CREATE INDEX IF NOT EXISTS order_payment_group_items_order_item_id_idx
  ON public.order_payment_group_items (order_item_id);
CREATE INDEX IF NOT EXISTS order_payment_tenders_payment_group_id_idx
  ON public.order_payment_tenders (payment_group_id);

ALTER TABLE public.order_payment_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_payment_group_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_payment_tenders ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.order_payment_groups,
  public.order_payment_group_items, public.order_payment_tenders
  FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.order_payment_groups,
  public.order_payment_group_items, public.order_payment_tenders
  TO authenticated;

DROP POLICY IF EXISTS order_payment_groups_staff_read ON public.order_payment_groups;
CREATE POLICY order_payment_groups_staff_read
  ON public.order_payment_groups FOR SELECT TO authenticated
  USING (public.current_staff_role() IN ('Administrador', 'Operador'));

DROP POLICY IF EXISTS order_payment_group_items_staff_read ON public.order_payment_group_items;
CREATE POLICY order_payment_group_items_staff_read
  ON public.order_payment_group_items FOR SELECT TO authenticated
  USING (public.current_staff_role() IN ('Administrador', 'Operador'));

DROP POLICY IF EXISTS order_payment_tenders_staff_read ON public.order_payment_tenders;
CREATE POLICY order_payment_tenders_staff_read
  ON public.order_payment_tenders FOR SELECT TO authenticated
  USING (public.current_staff_role() IN ('Administrador', 'Operador'));

CREATE OR REPLACE FUNCTION public.record_order_split_payment(
  p_order_id integer,
  p_groups jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_staff_id integer;
  v_order record;
  v_group jsonb;
  v_item jsonb;
  v_tender jsonb;
  v_group_id bigint;
  v_order_item_id integer;
  v_quantity integer;
  v_item_quantity integer;
  v_unit_price numeric(10, 2);
  v_subtotal numeric(10, 2);
  v_group_total numeric(10, 2);
  v_tender_total numeric(10, 2);
  v_order_total numeric(10, 2) := 0;
  v_assigned_quantity integer;
  v_payment_method text;
  v_order_payment_method text;
  v_amount numeric(10, 2);
  v_seen_items integer[];
  v_seen_methods text[];
  v_distinct_methods integer;
  v_table_id integer;
BEGIN
  v_staff_id := public.current_staff_id();
  IF v_staff_id IS NULL OR COALESCE(public.current_staff_role(), '') NOT IN ('Administrador', 'Operador') THEN
    RAISE EXCEPTION 'Active restaurant staff is required' USING ERRCODE = '42501';
  END IF;
  IF jsonb_typeof(p_groups) IS DISTINCT FROM 'array' OR jsonb_array_length(p_groups) = 0 THEN
    RAISE EXCEPTION 'At least one payment group is required';
  END IF;

  SELECT id, status, total_amount, table_id
  INTO v_order
  FROM public.orders
  WHERE id = p_order_id
  FOR UPDATE;
  IF NOT FOUND OR v_order.status <> 'servido' THEN
    RAISE EXCEPTION 'Only served orders can be paid';
  END IF;

  FOR v_group IN SELECT value FROM jsonb_array_elements(p_groups)
  LOOP
    IF jsonb_typeof(v_group -> 'items') IS DISTINCT FROM 'array'
      OR jsonb_array_length(v_group -> 'items') = 0
      OR jsonb_typeof(v_group -> 'tenders') IS DISTINCT FROM 'array'
      OR jsonb_array_length(v_group -> 'tenders') = 0 THEN
      RAISE EXCEPTION 'Each payment group needs items and payment methods';
    END IF;

    v_group_total := 0;
    v_seen_items := ARRAY[]::integer[];
    INSERT INTO public.order_payment_groups (order_id, user_id, payer_name, group_amount)
    VALUES (p_order_id, v_staff_id, NULLIF(btrim(v_group ->> 'payer_name'), ''), 0)
    RETURNING id INTO v_group_id;

    FOR v_item IN SELECT value FROM jsonb_array_elements(v_group -> 'items')
    LOOP
      v_order_item_id := (v_item ->> 'order_item_id')::integer;
      v_quantity := (v_item ->> 'quantity')::integer;
      IF v_order_item_id IS NULL OR v_quantity IS NULL OR v_quantity <= 0 THEN
        RAISE EXCEPTION 'Invalid product quantity in payment group';
      END IF;
      IF v_order_item_id = ANY(v_seen_items) THEN
        RAISE EXCEPTION 'A product may appear only once in each payment group';
      END IF;
      v_seen_items := array_append(v_seen_items, v_order_item_id);

      SELECT quantity, unit_price
      INTO v_item_quantity, v_unit_price
      FROM public.order_items
      WHERE id = v_order_item_id AND order_id = p_order_id
      FOR UPDATE;
      IF NOT FOUND THEN
        RAISE EXCEPTION 'A selected product does not belong to this order';
      END IF;

      v_subtotal := round(v_unit_price * v_quantity, 2);
      v_group_total := v_group_total + v_subtotal;
      INSERT INTO public.order_payment_group_items
        (payment_group_id, order_item_id, quantity, unit_price, subtotal)
      VALUES
        (v_group_id, v_order_item_id, v_quantity, v_unit_price, v_subtotal);
    END LOOP;

    IF v_group_total <= 0 THEN
      RAISE EXCEPTION 'Payment group total must be greater than zero';
    END IF;

    v_tender_total := 0;
    v_seen_methods := ARRAY[]::text[];
    FOR v_tender IN SELECT value FROM jsonb_array_elements(v_group -> 'tenders')
    LOOP
      v_payment_method := v_tender ->> 'payment_method';
      v_amount := round((v_tender ->> 'amount')::numeric, 2);
      IF v_payment_method NOT IN ('efectivo', 'tarjeta', 'transferencia')
        OR v_amount IS NULL OR v_amount <= 0 THEN
        RAISE EXCEPTION 'Invalid payment method or amount';
      END IF;
      IF v_payment_method = ANY(v_seen_methods) THEN
        RAISE EXCEPTION 'Each payment method may appear only once per group';
      END IF;
      v_seen_methods := array_append(v_seen_methods, v_payment_method);
      v_tender_total := v_tender_total + v_amount;
      INSERT INTO public.order_payment_tenders (payment_group_id, payment_method, amount)
      VALUES (v_group_id, v_payment_method, v_amount);
    END LOOP;

    IF round(v_tender_total, 2) <> round(v_group_total, 2) THEN
      RAISE EXCEPTION 'Payment methods must add up exactly to each person''s share';
    END IF;

    UPDATE public.order_payment_groups
    SET group_amount = v_group_total
    WHERE id = v_group_id;
    v_order_total := v_order_total + v_group_total;
  END LOOP;

  FOR v_order_item_id, v_item_quantity IN
    SELECT id, quantity FROM public.order_items WHERE order_id = p_order_id
  LOOP
    SELECT COALESCE(SUM(group_item.quantity), 0)
    INTO v_assigned_quantity
    FROM public.order_payment_group_items AS group_item
    JOIN public.order_payment_groups AS payment_group
      ON payment_group.id = group_item.payment_group_id
    WHERE payment_group.order_id = p_order_id
      AND group_item.order_item_id = v_order_item_id;
    IF v_assigned_quantity <> v_item_quantity THEN
      RAISE EXCEPTION 'Every product quantity must be assigned exactly once';
    END IF;
  END LOOP;

  IF round(v_order_total, 2) <> round(v_order.total_amount, 2) THEN
    RAISE EXCEPTION 'Payment groups must add up exactly to the order total';
  END IF;

  SELECT count(DISTINCT payment_tender.payment_method), min(payment_tender.payment_method)
  INTO v_distinct_methods, v_order_payment_method
  FROM public.order_payment_tenders AS payment_tender
  JOIN public.order_payment_groups AS payment_group
    ON payment_group.id = payment_tender.payment_group_id
  WHERE payment_group.order_id = p_order_id;

  UPDATE public.orders
  SET status = 'pagado',
      payment_method = CASE
        WHEN v_distinct_methods = 1 THEN v_order_payment_method
        ELSE 'mixto'
      END,
      paid_at = CURRENT_TIMESTAMP,
      updated_at = CURRENT_TIMESTAMP
  WHERE id = p_order_id;

  v_table_id := v_order.table_id;
  IF v_table_id IS NOT NULL AND NOT EXISTS (
    SELECT 1
    FROM public.orders
    WHERE table_id = v_table_id AND status IN ('armado', 'en_preparacion', 'servido')
  ) THEN
    UPDATE public.restaurant_tables SET status = 'disponible' WHERE id = v_table_id;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.record_order_split_payment(integer, jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.record_order_split_payment(integer, jsonb) TO authenticated;

-- Las ventas mixtas se contabilizan desde sus medios reales para el arqueo.
CREATE OR REPLACE FUNCTION public.close_cash_closure(
  p_counted_cash numeric,
  p_notes text DEFAULT NULL
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_staff_id integer;
  v_closure record;
  v_cash_sales numeric(10, 2) := 0;
  v_card_sales numeric(10, 2) := 0;
  v_other_sales numeric(10, 2) := 0;
  v_mixed_cash_sales numeric(10, 2) := 0;
  v_mixed_card_sales numeric(10, 2) := 0;
  v_mixed_other_sales numeric(10, 2) := 0;
  v_total_expenses numeric(10, 2) := 0;
  v_expected_cash numeric(10, 2);
BEGIN
  v_staff_id := public.current_staff_id();
  IF v_staff_id IS NULL OR COALESCE(public.current_staff_role(), '') NOT IN ('Administrador', 'Operador') THEN
    RAISE EXCEPTION 'Active restaurant staff is required' USING ERRCODE = '42501';
  END IF;
  IF p_counted_cash IS NULL OR p_counted_cash < 0 THEN
    RAISE EXCEPTION 'Counted cash must be zero or greater';
  END IF;

  SELECT * INTO v_closure
  FROM public.cash_closures
  WHERE status = 'abierta'
  ORDER BY opened_at
  LIMIT 1
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'There is no open cash register';
  END IF;

  SELECT COALESCE(SUM(total_amount), 0) INTO v_cash_sales
  FROM public.orders
  WHERE status = 'pagado' AND payment_method = 'efectivo'
    AND paid_at >= v_closure.opened_at AND paid_at <= CURRENT_TIMESTAMP;

  SELECT COALESCE(SUM(total_amount), 0) INTO v_card_sales
  FROM public.orders
  WHERE status = 'pagado' AND payment_method = 'tarjeta'
    AND paid_at >= v_closure.opened_at AND paid_at <= CURRENT_TIMESTAMP;

  SELECT COALESCE(SUM(total_amount), 0) INTO v_other_sales
  FROM public.orders
  WHERE status = 'pagado'
    AND payment_method NOT IN ('efectivo', 'tarjeta', 'mixto')
    AND paid_at >= v_closure.opened_at AND paid_at <= CURRENT_TIMESTAMP;

  SELECT
    COALESCE(SUM(payment_tender.amount) FILTER (WHERE payment_tender.payment_method = 'efectivo'), 0),
    COALESCE(SUM(payment_tender.amount) FILTER (WHERE payment_tender.payment_method = 'tarjeta'), 0),
    COALESCE(SUM(payment_tender.amount) FILTER (WHERE payment_tender.payment_method = 'transferencia'), 0)
  INTO v_mixed_cash_sales, v_mixed_card_sales, v_mixed_other_sales
  FROM public.order_payment_tenders AS payment_tender
  JOIN public.order_payment_groups AS payment_group
    ON payment_group.id = payment_tender.payment_group_id
  JOIN public.orders AS payment_order
    ON payment_order.id = payment_group.order_id
  WHERE payment_order.status = 'pagado'
    AND payment_order.payment_method = 'mixto'
    AND payment_order.paid_at >= v_closure.opened_at
    AND payment_order.paid_at <= CURRENT_TIMESTAMP;

  v_cash_sales := v_cash_sales + v_mixed_cash_sales;
  v_card_sales := v_card_sales + v_mixed_card_sales;
  v_other_sales := v_other_sales + v_mixed_other_sales;

  SELECT COALESCE(SUM(amount), 0) INTO v_total_expenses
  FROM public.expenses
  WHERE created_at >= v_closure.opened_at AND created_at <= CURRENT_TIMESTAMP;

  v_expected_cash := v_closure.opening_amount + v_cash_sales - v_total_expenses;

  UPDATE public.cash_closures
  SET total_cash_sales = v_cash_sales,
      total_card_sales = v_card_sales,
      total_other_sales = v_other_sales,
      total_expenses = v_total_expenses,
      expected_cash = v_expected_cash,
      counted_cash = p_counted_cash,
      difference = p_counted_cash - v_expected_cash,
      notes = NULLIF(btrim(p_notes), ''),
      status = 'cerrada',
      closed_at = CURRENT_TIMESTAMP
  WHERE id = v_closure.id;

  RETURN v_closure.id;
END;
$$;

REVOKE ALL ON FUNCTION public.close_cash_closure(numeric, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.close_cash_closure(numeric, text) TO authenticated;

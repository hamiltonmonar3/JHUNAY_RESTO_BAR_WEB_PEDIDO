CREATE TABLE public.reservations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name text NOT NULL CHECK (length(btrim(customer_name)) > 0),
  phone text,
  reservation_date date NOT NULL,
  reservation_time time NOT NULL,
  people_count integer NOT NULL CHECK (people_count > 0),
  deposit numeric(10, 2) NOT NULL DEFAULT 0 CHECK (deposit >= 0),
  notes text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.reservations ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.reservations TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.reservations_id_seq TO authenticated;

CREATE POLICY reservations_staff_manage
  ON public.reservations FOR ALL TO authenticated
  USING (public.current_staff_role() IN ('Administrador', 'Operador'))
  WITH CHECK (public.current_staff_role() IN ('Administrador', 'Operador'));

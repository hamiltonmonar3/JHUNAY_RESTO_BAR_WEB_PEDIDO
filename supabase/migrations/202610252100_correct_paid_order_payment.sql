CREATE TABLE IF NOT EXISTS public.order_payment_corrections (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES public.orders(id),
  previous_payment_method text NOT NULL,
  new_payment_method text NOT NULL,
  previous_tenders jsonb NOT NULL,
  new_tenders jsonb NOT NULL,
  reason text NOT NULL CHECK (char_length(btrim(reason)) > 0),
  corrected_by integer REFERENCES public.users(id),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS order_payment_corrections_order_id_created_at_idx
  ON public.order_payment_corrections (order_id, created_at DESC);

ALTER TABLE public.order_payment_corrections ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.order_payment_corrections FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.order_payment_corrections TO authenticated;

DROP POLICY IF EXISTS order_payment_corrections_admin_read ON public.order_payment_corrections;
CREATE POLICY order_payment_corrections_admin_read
  ON public.order_payment_corrections FOR SELECT TO authenticated
  USING (public.current_staff_role() = 'Administrador');

CREATE OR REPLACE FUNCTION public.correct_paid_order_payment(
  p_order_id integer,
  p_tenders jsonb,
  p_reason text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_staff_id integer;
  v_order record;
  v_tender jsonb;
  v_group record;
  v_methods text[] := ARRAY[]::text[];
  v_amounts numeric[] := ARRAY[]::numeric[];
  v_method text;
  v_amount numeric;
  v_groups_total numeric;
  v_remaining_group numeric;
  v_applied numeric;
  v_new_payment_method text;
  v_method_count integer := 0;
  v_group_count integer := 0;
  v_index integer;
  v_new_group_id bigint;
  v_previous_tenders jsonb;
  v_new_tenders jsonb;
BEGIN
  v_staff_id := public.current_staff_id();
  IF v_staff_id IS NULL OR public.current_staff_role() IS DISTINCT FROM 'Administrador' THEN
    RAISE EXCEPTION 'Administrator role is required' USING ERRCODE = '42501';
  END IF;
  IF p_tenders IS NULL OR jsonb_typeof(p_tenders) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Payment methods must be an array';
  END IF;
  IF jsonb_array_length(p_tenders) NOT BETWEEN 1 AND 3 THEN
    RAISE EXCEPTION 'Provide between one and three payment methods';
  END IF;
  IF p_reason IS NULL OR btrim(p_reason) = '' THEN
    RAISE EXCEPTION 'A correction reason is required';
  END IF;

  SELECT id, status, total_amount, payment_method
  INTO v_order
  FROM public.orders
  WHERE id = p_order_id
  FOR UPDATE;
  IF NOT FOUND OR v_order.status <> 'pagado' THEN
    RAISE EXCEPTION 'Only paid orders can have their payment corrected';
  END IF;

  FOR v_tender IN SELECT value FROM jsonb_array_elements(p_tenders)
  LOOP
    v_method := v_tender ->> 'payment_method';
    BEGIN
      v_amount := round((v_tender ->> 'amount')::numeric, 2);
    EXCEPTION WHEN invalid_text_representation OR numeric_value_out_of_range THEN
      RAISE EXCEPTION 'Invalid payment amount';
    END;
    IF v_method IS NULL OR v_method NOT IN ('efectivo', 'tarjeta', 'transferencia')
      OR v_amount IS NULL OR v_amount <= 0 THEN
      RAISE EXCEPTION 'Invalid payment method or amount';
    END IF;
    IF v_method = ANY(v_methods) THEN
      RAISE EXCEPTION 'Each payment method may appear only once';
    END IF;
    v_methods := array_append(v_methods, v_method);
    v_amounts := array_append(v_amounts, v_amount);
    v_method_count := v_method_count + 1;
  END LOOP;

  IF round((SELECT COALESCE(sum(amount_value), 0) FROM unnest(v_amounts) AS amount_rows(amount_value)), 2)
    <> round(v_order.total_amount, 2) THEN
    RAISE EXCEPTION 'Payment methods must add up exactly to the order total';
  END IF;

  SELECT COALESCE(
    jsonb_agg(
      jsonb_build_object(
        'group_id', payment_group.id,
        'payer_name', payment_group.payer_name,
        'payment_method', payment_tender.payment_method,
        'amount', payment_tender.amount
      ) ORDER BY payment_group.id, payment_tender.id
    ),
    '[]'::jsonb
  )
  INTO v_previous_tenders
  FROM public.order_payment_groups AS payment_group
  JOIN public.order_payment_tenders AS payment_tender
    ON payment_tender.payment_group_id = payment_group.id
  WHERE payment_group.order_id = p_order_id;

  IF jsonb_array_length(v_previous_tenders) = 0 THEN
    IF v_order.payment_method IS NULL
      OR v_order.payment_method NOT IN ('efectivo', 'tarjeta', 'transferencia') THEN
      RAISE EXCEPTION 'The existing payment breakdown is unavailable';
    END IF;
    v_previous_tenders := jsonb_build_array(jsonb_build_object(
      'payment_method', v_order.payment_method,
      'amount', v_order.total_amount
    ));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.order_payment_groups WHERE order_id = p_order_id) THEN
    INSERT INTO public.order_payment_groups (order_id, user_id, payer_name, group_amount)
    VALUES (p_order_id, v_staff_id, 'Pago corregido', v_order.total_amount)
    RETURNING id INTO v_new_group_id;

    INSERT INTO public.order_payment_group_items
      (payment_group_id, order_item_id, quantity, unit_price, subtotal)
    SELECT v_new_group_id, item.id, item.quantity, item.unit_price,
      round(item.unit_price * item.quantity, 2)
    FROM public.order_items AS item
    WHERE item.order_id = p_order_id;
  END IF;

  SELECT round(COALESCE(sum(group_amount), 0), 2)
  INTO v_groups_total
  FROM public.order_payment_groups
  WHERE order_id = p_order_id;
  IF v_groups_total <> round(v_order.total_amount, 2) THEN
    RAISE EXCEPTION 'Existing payment groups do not match the order total';
  END IF;

  DELETE FROM public.order_payment_tenders AS payment_tender
  USING public.order_payment_groups AS payment_group
  WHERE payment_tender.payment_group_id = payment_group.id
    AND payment_group.order_id = p_order_id;

  FOR v_group IN
    SELECT id, group_amount
    FROM public.order_payment_groups
    WHERE order_id = p_order_id
    ORDER BY id
  LOOP
    v_group_count := v_group_count + 1;
    v_remaining_group := round(v_group.group_amount, 2);
    FOR v_index IN 1..v_method_count
    LOOP
      EXIT WHEN v_remaining_group <= 0;
      v_applied := least(v_remaining_group, v_amounts[v_index]);
      IF v_applied > 0 THEN
        INSERT INTO public.order_payment_tenders (payment_group_id, payment_method, amount)
        VALUES (v_group.id, v_methods[v_index], v_applied);
        v_amounts[v_index] := round(v_amounts[v_index] - v_applied, 2);
        v_remaining_group := round(v_remaining_group - v_applied, 2);
      END IF;
    END LOOP;
    IF v_remaining_group <> 0 THEN
      RAISE EXCEPTION 'Payment groups do not match the order total';
    END IF;
  END LOOP;

  IF v_group_count = 0 THEN
    RAISE EXCEPTION 'No payment group was available to correct';
  END IF;

  SELECT CASE WHEN count(DISTINCT payment_tender.payment_method) = 1
    THEN min(payment_tender.payment_method)
    ELSE 'mixto'
  END
  INTO v_new_payment_method
  FROM public.order_payment_tenders AS payment_tender
  JOIN public.order_payment_groups AS payment_group
    ON payment_group.id = payment_tender.payment_group_id
  WHERE payment_group.order_id = p_order_id;

  SELECT COALESCE(
    jsonb_agg(
      jsonb_build_object(
        'group_id', payment_group.id,
        'payer_name', payment_group.payer_name,
        'payment_method', payment_tender.payment_method,
        'amount', payment_tender.amount
      ) ORDER BY payment_group.id, payment_tender.id
    ),
    '[]'::jsonb
  )
  INTO v_new_tenders
  FROM public.order_payment_groups AS payment_group
  JOIN public.order_payment_tenders AS payment_tender
    ON payment_tender.payment_group_id = payment_group.id
  WHERE payment_group.order_id = p_order_id;

  UPDATE public.orders
  SET payment_method = v_new_payment_method,
      updated_at = CURRENT_TIMESTAMP
  WHERE id = p_order_id;

  INSERT INTO public.order_payment_corrections (
    order_id,
    previous_payment_method,
    new_payment_method,
    previous_tenders,
    new_tenders,
    reason,
    corrected_by
  )
  VALUES (
    p_order_id,
    v_order.payment_method,
    v_new_payment_method,
    v_previous_tenders,
    v_new_tenders,
    btrim(p_reason),
    v_staff_id
  );
END;
$$;

REVOKE ALL ON FUNCTION public.correct_paid_order_payment(integer, jsonb, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.correct_paid_order_payment(integer, jsonb, text) TO authenticated;

CREATE TABLE IF NOT EXISTS public.personas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name text NOT NULL CHECK (char_length(btrim(full_name)) > 0),
  identification text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS personas_identification_key
  ON public.personas (identification)
  WHERE identification IS NOT NULL AND btrim(identification) <> '';

CREATE TABLE IF NOT EXISTS public.persona_financial_movements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  persona_id integer NOT NULL REFERENCES public.personas(id) ON DELETE RESTRICT,
  movement_type text NOT NULL CHECK (movement_type IN ('por_cobrar', 'por_pagar', 'descuento')),
  amount numeric(10, 2) NOT NULL CHECK (amount > 0),
  description text NOT NULL CHECK (char_length(btrim(description)) > 0),
  movement_date date NOT NULL,
  created_by integer REFERENCES public.users(id),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS persona_financial_movements_date_idx
  ON public.persona_financial_movements (movement_date DESC, id DESC);
CREATE INDEX IF NOT EXISTS persona_financial_movements_person_date_idx
  ON public.persona_financial_movements (persona_id, movement_date DESC, id DESC);

ALTER TABLE public.personas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.persona_financial_movements ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.personas, public.persona_financial_movements
  FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.personas, public.persona_financial_movements TO authenticated;

DROP POLICY IF EXISTS personas_admin_read ON public.personas;
CREATE POLICY personas_admin_read
  ON public.personas FOR SELECT TO authenticated
  USING (public.current_staff_role() = 'Administrador');

DROP POLICY IF EXISTS persona_financial_movements_admin_read ON public.persona_financial_movements;
CREATE POLICY persona_financial_movements_admin_read
  ON public.persona_financial_movements FOR SELECT TO authenticated
  USING (public.current_staff_role() = 'Administrador');

CREATE OR REPLACE FUNCTION public.save_persona(
  p_persona_id integer,
  p_full_name text,
  p_identification text,
  p_is_active boolean
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_persona_id integer;
BEGIN
  IF public.current_staff_role() IS DISTINCT FROM 'Administrador' THEN
    RAISE EXCEPTION 'Administrator role is required' USING ERRCODE = '42501';
  END IF;
  IF p_full_name IS NULL OR btrim(p_full_name) = '' THEN
    RAISE EXCEPTION 'Person name is required';
  END IF;
  IF p_is_active IS NULL THEN
    RAISE EXCEPTION 'Person status is required';
  END IF;

  IF p_persona_id IS NULL THEN
    INSERT INTO public.personas (full_name, identification, is_active)
    VALUES (
      btrim(p_full_name),
      NULLIF(btrim(COALESCE(p_identification, '')), ''),
      p_is_active
    )
    RETURNING id INTO v_persona_id;
  ELSE
    UPDATE public.personas
    SET full_name = btrim(p_full_name),
        identification = NULLIF(btrim(COALESCE(p_identification, '')), ''),
        is_active = p_is_active
    WHERE id = p_persona_id
    RETURNING id INTO v_persona_id;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Person not found';
    END IF;
  END IF;

  RETURN v_persona_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.delete_persona(p_persona_id integer)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF public.current_staff_role() IS DISTINCT FROM 'Administrador' THEN
    RAISE EXCEPTION 'Administrator role is required' USING ERRCODE = '42501';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.persona_financial_movements WHERE persona_id = p_persona_id
  ) THEN
    RAISE EXCEPTION 'Person has financial movements; deactivate the person instead';
  END IF;

  DELETE FROM public.personas WHERE id = p_persona_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Person not found';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_persona_financial_movement(
  p_persona_id integer,
  p_movement_type text,
  p_amount numeric,
  p_description text,
  p_movement_date date
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_created_by integer;
  v_movement_id bigint;
BEGIN
  IF public.current_staff_role() IS DISTINCT FROM 'Administrador' THEN
    RAISE EXCEPTION 'Administrator role is required' USING ERRCODE = '42501';
  END IF;
  IF p_persona_id IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.personas WHERE id = p_persona_id AND is_active
  ) THEN
    RAISE EXCEPTION 'Active person not found';
  END IF;
  IF p_movement_type IS NULL OR p_movement_type NOT IN ('por_cobrar', 'por_pagar', 'descuento') THEN
    RAISE EXCEPTION 'Unsupported person financial movement type';
  END IF;
  IF p_amount IS NULL OR p_amount <= 0 THEN
    RAISE EXCEPTION 'Movement amount must be greater than zero';
  END IF;
  IF p_description IS NULL OR btrim(p_description) = '' THEN
    RAISE EXCEPTION 'Movement description is required';
  END IF;
  IF p_movement_date IS NULL THEN
    RAISE EXCEPTION 'Movement date is required';
  END IF;

  v_created_by := public.current_staff_id();
  INSERT INTO public.persona_financial_movements (
    persona_id, movement_type, amount, description, movement_date, created_by
  )
  VALUES (
    p_persona_id, p_movement_type, p_amount, btrim(p_description), p_movement_date, v_created_by
  )
  RETURNING id INTO v_movement_id;

  RETURN v_movement_id;
END;
$$;

REVOKE ALL ON FUNCTION public.save_persona(integer, text, text, boolean) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.delete_persona(integer) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.record_persona_financial_movement(integer, text, numeric, text, date) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.save_persona(integer, text, text, boolean) TO authenticated;
GRANT EXECUTE ON FUNCTION public.delete_persona(integer) TO authenticated;
GRANT EXECUTE ON FUNCTION public.record_persona_financial_movement(integer, text, numeric, text, date) TO authenticated;
